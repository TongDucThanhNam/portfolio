import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const CHARACTER_RAMP = "@%#*+=-:.";
const COLUMNS = 120;
const CHARACTER_WIDTH = 0.6;
const ALPHA_CUTOFF = 24;

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(scriptDirectory, "..");
const sourcePath = resolve(
	repositoryRoot,
	"apps/web/public/images/avatar-cutout.webp",
);
const outputPath = resolve(
	repositoryRoot,
	"apps/web/public/images/avatar-ascii.svg",
);

const source = sharp(sourcePath);
const metadata = await source.metadata();

if (!metadata.width || !metadata.height) {
	throw new Error(`Could not read portrait dimensions from ${sourcePath}`);
}

// Monospace glyphs are roughly 0.6 as wide as they are tall. Sampling fewer
// rows compensates for that ratio so the resulting character grid keeps the
// source portrait's proportions when rendered.
const rows = Math.round(
	COLUMNS * CHARACTER_WIDTH * (metadata.height / metadata.width),
);

const { data, info } = await source
	.resize({
		width: COLUMNS,
		height: rows,
		fit: "fill",
		kernel: sharp.kernel.lanczos3,
	})
	.ensureAlpha()
	.raw()
	.toBuffer({ resolveWithObject: true });

const asciiRows = Array.from({ length: info.height }, (_, y) => {
	let row = "";

	for (let x = 0; x < info.width; x += 1) {
		const offset = (y * info.width + x) * info.channels;
		const red = data[offset];
		const green = data[offset + 1];
		const blue = data[offset + 2];
		const alpha = data[offset + 3];

		if (alpha < ALPHA_CUTOFF) {
			row += " ";
			continue;
		}

		const luminance = red * 0.2126 + green * 0.7152 + blue * 0.0722;
		const compositedLuminance = 255 - (alpha / 255) * (255 - luminance);
		const contrasted = Math.max(
			0,
			Math.min(255, (compositedLuminance - 128) * 1.18 + 128),
		);
		const rampIndex = Math.round(
			(contrasted / 255) * (CHARACTER_RAMP.length - 1),
		);

		row += CHARACTER_RAMP[rampIndex];
	}

	return row.trimEnd();
});

const escapeXml = (value) =>
	value
		.replaceAll("&", "&amp;")
		.replaceAll("<", "&lt;")
		.replaceAll(">", "&gt;");

const svgWidth = COLUMNS * CHARACTER_WIDTH;
const tspans = asciiRows
	.map(
		(row, index) =>
			`<tspan x="0" y="${index + 0.84}">${escapeXml(row || " ")}</tspan>`,
	)
	.join("");

const svg = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-ascii-portrait.mjs. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${svgWidth} ${rows}" preserveAspectRatio="xMidYMin meet">
  <text fill="#16140f" font-family="Fira Code, Cascadia Mono, Courier New, monospace" font-size="1" font-weight="500" xml:space="preserve" text-rendering="geometricPrecision">${tspans}</text>
</svg>
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, svg, "utf8");

console.log(`Generated ${outputPath} from ${COLUMNS} columns × ${rows} rows.`);
